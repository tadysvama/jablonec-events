// Funkce pro simulaci fetchování – vrátí události podle filtrů
export function filterEvents(
  events: Event[],
  opts: {
    category?: string;
    search?: string;
    sortBy?: 'date' | 'popularity' | 'points';
  } = {}
): Event[] {
  let result = [...events];

  if (opts.category && opts.category !== 'all') {
    result = result.filter((e) => e.category === opts.category);
  }

  if (opts.search) {
    const q = opts.search.toLowerCase();
    result = result.filter(
      (e) =>
        e.title.toLowerCase().includes(q) ||
        e.description.toLowerCase().includes(q) ||
        e.location.toLowerCase().includes(q)
    );
  }

  switch (opts.sortBy) {
    case 'popularity':
      result.sort((a, b) => b.attendeeCount - a.attendeeCount);
      break;
    case 'points':
      result.sort((a, b) => b.basePoints - a.basePoints);
      break;
    case 'date':
    default:
      result.sort((a, b) => new Date(a.startsAt).getTime() - new Date(b.startsAt).getTime());
  }

  return result;
}

export function getEventById(id: string): Event | undefined {
  return MOCK_EVENTS.find((e) => e.id === id);
}
